import AppKit
import ApplicationServices
import Carbon

/// Accessibility ("Bedienungshilfen"): needed only to press ⌘C/⌘V for the person. Asked for once, with our own
/// explanation first; without it the text goes through the window and the clipboard.
@MainActor
enum Access {
    private static let askedKey = "asked.accessibility"

    static var trusted: Bool { AXIsProcessTrusted() }

    /// Once per installation: explain, then macOS's own request. Later only the settings window asks again.
    static func askOnce() {
        guard !trusted, !UserDefaults.standard.bool(forKey: askedKey) else { return }
        UserDefaults.standard.set(true, forKey: askedKey)
        explainAndAsk()
    }

    static func explainAndAsk() {
        NSApp.activate(ignoringOtherApps: true)
        let a = NSAlert()
        a.messageText = "Bedienungshilfen für den Spark-Begleiter erlauben?"
        a.informativeText = """
            Damit der Begleiter markierten Text selbst kopieren und das Ergebnis an der Schreibmarke einfügen kann, \
            drückt er für dich ⌘C und ⌘V. Dafür braucht macOS deine Freigabe unter Systemeinstellungen → \
            Datenschutz & Sicherheit → Bedienungshilfen.

            Der Begleiter liest dabei nichts mit und sieht nur den Text, den du ihm gibst.

            Ohne Freigabe geht es auch: Text im Fenster einfügen, das Ergebnis liegt dann in der Zwischenablage. \
            „Mit Spark verbessern“ im Dienste-Menü braucht keine Freigabe.
            """
        a.addButton(withTitle: "Freigabe öffnen")
        a.addButton(withTitle: "Später")
        if a.runModal() == .alertFirstButtonReturn {
            // the value of kAXTrustedCheckOptionPrompt
            let opts = ["AXTrustedCheckOptionPrompt": true] as CFDictionary
            if !AXIsProcessTrustedWithOptions(opts) {
                openSettings()
            }
        }
    }

    static func openSettings() {
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }
}

/// Key presses for the person (needs Accessibility).
enum Keys {
    static func press(_ code: Int, flags: CGEventFlags = .maskCommand) {
        let src = CGEventSource(stateID: .hidSystemState)
        guard let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(code), keyDown: true),
              let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(code), keyDown: false) else { return }
        down.flags = flags
        up.flags = flags
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
    }

    /// Waits (at most a second) until ⌥, ⌃ and ⇧ of the hotkey are let go, so they do not mix into ⌘C/⌘V.
    static func waitForModifiers() async {
        for _ in 0..<20 {
            let f = CGEventSource.flagsState(.combinedSessionState)
            if !f.contains(.maskAlternate) && !f.contains(.maskControl) && !f.contains(.maskShift) { return }
            try? await Task.sleep(nanoseconds: 50_000_000)
        }
    }
}

/// The clipboard: saved before and restored after every copy/paste of our own. Our temporary entries are marked
/// transient/concealed (nspasteboard.org), so clipboard managers leave them out of their history.
@MainActor
enum Clip {
    struct Snapshot {
        fileprivate let items: [[(NSPasteboard.PasteboardType, Data)]]
    }

    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static func snapshot() -> Snapshot {
        let items = (NSPasteboard.general.pasteboardItems ?? []).map { item -> [(NSPasteboard.PasteboardType, Data)] in
            item.types.compactMap { t in item.data(forType: t).map { (t, $0) } }
        }
        return Snapshot(items: items)
    }

    static func restore(_ s: Snapshot) {
        let pb = NSPasteboard.general
        pb.clearContents()
        let objects = s.items.map { pairs -> NSPasteboardItem in
            let it = NSPasteboardItem()
            for (t, d) in pairs { it.setData(d, forType: t) }
            return it
        }
        if !objects.isEmpty {
            pb.writeObjects(objects)
        }
    }

    /// A temporary entry, only for our own ⌘V.
    static func putTemporary(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.declareTypes([.string, transient, concealed, autoGenerated], owner: nil)
        pb.setString(text, forType: .string)
        pb.setData(Data(), forType: transient)
        pb.setData(Data(), forType: concealed)
        pb.setData(Data(), forType: autoGenerated)
    }

    /// A normal entry the person pastes themselves ("Text ist in der Zwischenablage").
    static func put(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
    }

    /// The marked text of the front program through ⌘C; the clipboard is as before afterwards. nil without
    /// Accessibility or when nothing is marked.
    static func copySelection() async -> String? {
        guard Access.trusted else { return nil }
        await Keys.waitForModifiers()
        let pb = NSPasteboard.general
        let saved = snapshot()
        let before = pb.changeCount
        Keys.press(kVK_ANSI_C)
        var text: String?
        for _ in 0..<20 {
            try? await Task.sleep(nanoseconds: 50_000_000)
            if pb.changeCount != before {
                try? await Task.sleep(nanoseconds: 60_000_000)
                text = pb.string(forType: .string)
                break
            }
        }
        if pb.changeCount != before {
            restore(saved)
        }
        return text
    }

    /// Puts the text at the cursor of `app` through ⌘V and restores the clipboard. Without Accessibility the
    /// text stays in the clipboard and false comes back.
    static func paste(_ text: String, into app: NSRunningApplication?) async -> Bool {
        guard Access.trusted else {
            put(text)
            return false
        }
        if let app, app != NSRunningApplication.current {
            app.activate(options: [])
            for _ in 0..<10 {
                try? await Task.sleep(nanoseconds: 50_000_000)
                if NSWorkspace.shared.frontmostApplication == app { break }
            }
            try? await Task.sleep(nanoseconds: 120_000_000)
        }
        await Keys.waitForModifiers()
        let saved = snapshot()
        putTemporary(text)
        let mine = NSPasteboard.general.changeCount
        Keys.press(kVK_ANSI_V)
        try? await Task.sleep(nanoseconds: 700_000_000)
        if NSPasteboard.general.changeCount == mine {
            restore(saved)
        }
        return true
    }
}
