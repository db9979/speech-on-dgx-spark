#!/bin/bash
# Builds "SparkHilfe.app" (Spontanhilfe S2c; universal: arm64 + x86_64, macOS 13+) with the Xcode command line tools
# only, from Sources/*.swift and the core shared with the Begleiter (tools/begleiter/mac/Sources/Sicht.swift):
#   tools/sparkhilfe/mac/build.sh          -> tools/sparkhilfe/mac/build/SparkHilfe.app (ad-hoc signed; only CI signs
#                                             it with the Developer ID, notarizes it and staples the ticket)
#   tools/sparkhilfe/mac/build.sh pruefung -> tools/sparkhilfe/mac/build-pruefung/pruefung (the self-test of its rules)
# The two colours of the frame and the bar come from the Begleiter's Theme.swift (one source): the lines are taken
# from there into build/Farben.swift; the build stops when they are not found.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
core="$root/tools/begleiter/mac/Sources"
out="$here/build"
[[ "${1:-}" == "pruefung" ]] && out="$here/build-pruefung"
app="$out/SparkHilfe.app"
min="13.0"

raw=$(tr -d '[:space:]' < "$root/app/VERSION" 2>/dev/null || true)
ver=$(printf '%s' "$raw" | sed -E 's/^[vV]//' | awk -F. '{ for (i = 1; i <= NF; i++) { $i = $i + 0 } ; print }' OFS=.)
[[ "$ver" =~ ^[0-9]+(\.[0-9]+){0,2}$ ]] || ver="0.0.0"
build="${GITHUB_RUN_NUMBER:-${ver##*.}}"
[[ "$build" =~ ^[0-9]+$ ]] || build="0"

rm -rf "$out"
mkdir -p "$out/obj"

# the colours of Theme.swift, nothing else (NSColor(hex:) and nsBad / nsOnAccent)
theme="$core/Theme.swift"
{
  echo "import AppKit"
  echo "// generated by tools/sparkhilfe/mac/build.sh from tools/begleiter/mac/Sources/Theme.swift"
  sed -n '/^extension NSColor {$/,/^}$/p' "$theme"
  echo "enum Theme {"
  grep -E '^    static let (nsBad|nsOnAccent) = NSColor\(hex: 0x[0-9a-fA-F]{6}\)$' "$theme"
  echo "}"
} > "$out/Farben.swift"
if [[ $(grep -c 'static let ns' "$out/Farben.swift") -ne 2 ]] || ! grep -q 'convenience init(hex:' "$out/Farben.swift"; then
  echo "Theme.swift: nsBad, nsOnAccent or NSColor(hex:) not found" >&2
  exit 1
fi

sdk=$(xcrun --sdk macosx --show-sdk-path)
sources=("$here"/Sources/*.swift "$core/Sicht.swift" "$out/Farben.swift")

if [[ "${1:-}" == "pruefung" ]]; then
  lib=()
  for f in "${sources[@]}"; do [[ "$(basename "$f")" == "Main.swift" ]] || lib+=("$f"); done
  xcrun --sdk macosx swiftc -sdk "$sdk" -target "$(uname -m)-apple-macos$min" -swift-version 5 \
    -module-name SparkHilfe -o "$out/pruefung" "$here/Pruefung/main.swift" "${lib[@]}"
  echo "== $out/pruefung"
  exit 0
fi

mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
for arch in arm64 x86_64; do
  echo "== swiftc $arch"
  xcrun --sdk macosx swiftc \
    -sdk "$sdk" \
    -target "$arch-apple-macos$min" \
    -swift-version 5 \
    -O -whole-module-optimization \
    -parse-as-library \
    -module-name SparkHilfe \
    -o "$out/obj/SparkHilfe-$arch" \
    "${sources[@]}"
done
lipo -create "$out/obj/SparkHilfe-arm64" "$out/obj/SparkHilfe-x86_64" -output "$app/Contents/MacOS/SparkHilfe"
lipo -info "$app/Contents/MacOS/SparkHilfe"

cp "$here/Info.plist" "$app/Contents/Info.plist"
plutil -replace CFBundleShortVersionString -string "$ver" "$app/Contents/Info.plist"
plutil -replace CFBundleVersion -string "$build" "$app/Contents/Info.plist"
plutil -lint "$app/Contents/Info.plist"
printf 'APPL????' > "$app/Contents/PkgInfo"

codesign --force --sign - "$app"
codesign --verify --strict --verbose=2 "$app"
echo "== $app ($ver, build $build)"
